    public static List<Province> Provinces() =>
        [.. Areas.Select(a => new Province(a.Code, a.Name))];

    /// <summary>
    /// An unknown province is an empty list, not an error: the caller is a
    /// dropdown that has simply not been given a choice yet.
    /// </summary>
    public static List<District> Districts(string provinceCode) =>
        [.. Areas.FirstOrDefault(a => a.Code == provinceCode).Districts?
            .Select(name => new District(provinceCode, name)) ?? []];
